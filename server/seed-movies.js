async function seed() {
  try {
    await initDatabase();
    console.log('数据库表已就绪');

    // 清空旧数据
    await pool.execute('DELETE FROM episodes');
    await pool.execute('DELETE FROM seasons');
    await pool.execute('DELETE FROM movies');

    // 插入电影
    for (const m of MOVIES) {
      await pool.execute(
        `INSERT INTO movies (id, title, original_title, overview, genre_ids, release_date,
         vote_average, language, origin_country, media_type, runtime, popularity, status)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'Released')`,
        m
      );
    }
    console.log(`✅ 插入 ${MOVIES.length} 部电影`);

    // 插入电视剧
    for (const t of TVS) {
      await pool.execute(
        `INSERT INTO movies (id, title, original_title, overview, genre_ids, release_date,
         vote_average, language, origin_country, media_type, runtime, popularity, status)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'Returning Series')`,
        t
      );
    }
    console.log(`✅ 插入 ${TVS.length} 部电视剧`);

    // 为电视剧插入季信息
    const tvIds = TVS.map(t => t[0]);
    for (const tid of tvIds) {
      for (let sn = 1; sn <= 3; sn++) {
        await pool.execute(
          'INSERT INTO seasons (movie_id, name, overview, air_date, season_number, episode_count, poster_path) VALUES (?, ?, ?, ?, ?, ?, ?)',
          [tid, `第${sn}季`, `第${sn}季剧情`, `202${4+sn}-05-01`, sn, 12 + sn * 6, '']
        );
      }
      // 插入下一集预告
      await pool.execute(
        'INSERT INTO episodes (movie_id, name, overview, air_date, episode_number, season_number, still_path, vote_average, runtime) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)',
        [tid, '新一集', '精彩即将上演...', '2026-07-08', 31, 3, '', 9.0, 45]
      );
    }
    console.log('✅ 插入季/集数据');

    console.log('═══════════════════════');
    console.log('  影视数据导入完成！');
    console.log(`  电影: ${MOVIES.length} 部`);
    console.log(`  电视剧: ${TVS.length} 部`);
    console.log('═══════════════════════');
    process.exit(0);
  } catch (err) {
    console.error('导入失败:', err.message);
    process.exit(1);
  }
}

seed();
